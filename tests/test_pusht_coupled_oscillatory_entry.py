def _legal_initial(model, source, *, time=TIME):
    q, v = np.asarray(source["q"], dtype=np.float64), np.asarray(source["v"], dtype=np.float64)
    np.testing.assert_array_equal(q, q.astype(np.float32))
    np.testing.assert_array_equal(v, v.astype(np.float32))
    address = int(model.jnt_qposadr[model.joint("object-free").id]) + 3
    assert address == 5 and q.shape == (9,) and v.shape == (8,)
    declared = q.copy()
    declared[address : address + 4] /= np.linalg.norm(declared[address : address + 4])
    assert (
        abs(np.dot(declared[address : address + 4], declared[address : address + 4]) - 1)
        < 64 * np.finfo(float).eps
    )
    assert np.max(abs(declared - q)) < 1e-7
    np.testing.assert_array_equal(declared[:address], q[:address])
    packed = declared.astype(np.float32).astype(np.float64)
    return MuJoCoInitialState(declared, v, time=time), packed


def test_real_rr_oscillatory_entry_closes_both_lanes_with_original_gates(record_property):
    import mujoco as mj

    original = next(scene for scene in manipulation_scenes() if scene.key == "pusht-planar")
    assert original.source_sha256 == SOURCE_SHA
    model = mj.MjModel.from_xml_string(original.mjcf)
    assert (model.nq, model.nv, model.nu, model.na) == (9, 8, 2, 0)
    spec, asset = build_scene_spec(original.mjcf), build_side_asset(model)
    assert spec.contact_capacity == 64 and spec.constraint_capacity == 512
    worlds, packed = [], {}
    for key, source in INPUTS.items():
        initial, packed[key] = _legal_initial(model, source)
        worlds.append(MuJoCoTyxWorldSpec(key, spec.key, initial))
        record_property(
            source["lane"] + "_source_q_fp32_bytes_preserved",
            packed[key].astype(np.float32).tobytes()
            == np.asarray(source["q"], np.float32).tobytes(),
        )
        record_property(source["lane"] + "_public_initial_q", packed[key].tolist())
        record_property(
            source["lane"] + "_normalization_max_abs", float(np.max(abs(packed[key] - source["q"])))
        )
    record_property(
        "real_case", "RR tick1147: same-entry-full feedback exhausted original 24 outer updates"
    )
    record_property(
        "initialization", "one FP64 unit declaration; exact declared-to-device q/v packing checked"
    )

    with MuJoCoTyxHeterogeneousBatch((spec,), tuple(worlds), mode="cuda") as batch:
        scene = MuJoCoTyxHeterogeneousAreaPressureScene(batch, {spec.key: (asset,)})
        assert scene.asset_sha256 == ASSET_SHA
        batch.set_controls(
            {
                key: MuJoCoControl(
                    source["ctrl"],
                    qfrc_applied=np.zeros(model.nv),
                    xfrc_applied=np.zeros((model.nbody, 6)),
                )
                for key, source in INPUTS.items()
            }
        )
        before = batch.integration_snapshot()
        for key, state in before.items():
            assert state.q.tobytes() == packed[key].tobytes()
            assert state.v.tobytes() == np.asarray(INPUTS[key]["v"], np.float64).tobytes()
            assert state.time == TIME and state.tick == 0
            np.testing.assert_array_equal(state.held_control.ctrl, INPUTS[key]["ctrl"])
            owner = batch._buckets[batch.layout[key].bucket]
            assert owner._plan.resident_native_contacts
            assert owner._plan.solver_iterations == 128
        revision = batch.checkpoint_revision
        # One fixed paired call. No retries, adaptive material changes, warm-up
        # trajectory, or extra single-lane attempts are hidden in this regression.
        assert scene.step(H, expected_revision=revision) == {5: True, 6: True}
        assert batch.checkpoint_revision == revision + 1
        after = batch.integration_snapshot()
        assert after[5].time == after[6].time
        for key in INPUTS:
            receipt = after[key].last_step
            solver = receipt.raw_contact_fields["area_friction_solver"]
            diagnostic = solver["raw_diagnostics"]
            meta, trace_meta, trace = (
                diagnostic["meta"],
                diagnostic["trace_meta"],
                diagnostic["trace"],
            )
            assert meta[0] == 0 and meta[3] == 1
            outer, calls = int(meta[1]), int(meta[2])
            assert 0 <= outer <= 24 and calls == outer + 1 <= 25
            assert trace_meta[calls - 1, 2] == 1
            assert trace[calls - 1, 10] <= np.float32(1e-6)
            assert trace[calls - 1, 11] <= np.float32(1e-7)
            assert np.all(trace[calls:] == 0) and np.all(trace_meta[calls:] == 0)
            assert solver["tolerance"] == 2e-5 and solver["normalized_residual"] <= 2e-5
            np.testing.assert_array_equal(receipt.stored_control.ctrl, INPUTS[key]["ctrl"])
            # Reuse the independent original-model M/J/R/aref, true triangle
            # integration and two FP64 roots, including every native row force,
            # both body Jacobians, moment arms, final-v law and FREE quaternion.
            audit = _audit(model, asset, before[key], after[key], scene.last_geometry[key][0])
            assert audit["samples"] > 0 and audit["normal"] > 0 and audit["tangent"] > 0
            if key == 5:
                assert audit["support"] > 0 and audit["native_rows"] == 24
            else:
                # Original-model contact detection finds no floor row on this
                # input. Only the side pressure acts on the object this step.
                assert not receipt.contacts and audit["native_rows"] == 0
                assert audit["support"] == 0 and np.any(trace_meta[:calls, 0] == 2)
                # Keeping the accepted forces and velocities while relabeling
                # the trial updates must fail the historical source check.
                claimed = trace_meta.copy()
                claimed[claimed[:, 0] == 2, 0] = 1
                forged = _solver_receipt(
                    receipt, {**solver, "raw_diagnostics": {**diagnostic, "trace_meta": claimed}}
                )
                owner = batch._buckets[batch.layout[key].bucket]
                with pytest.raises(
                    ValueError, match="resident baseline/outer area-load source binding"
                ):
                    validate_friction_receipt(owner, key, forged, owner._data[key])
            dyn = receipt.dynamics
            (pair,) = receipt.raw_contact_fields["area_friction"]
            point_q = np.einsum(
                "sij,si->j", pair["jacobian_a"] - pair["jacobian_b"], pair["force_on_a"]
            )
            native_q = sum(
                (row.force * row.jacobian for row in receipt.constraints), np.zeros(model.nv)
            )
            impulse = solver["h_s"] * (dyn.applied + dyn.passive - dyn.bias + native_q + point_q)
            response = dyn.mass_matrix + solver["h_s"] * np.diag(model.dof_damping)
            np.testing.assert_allclose(
                response @ (after[key].v - before[key].v), impulse, rtol=5e-5, atol=2e-7
            )
            record_property(INPUTS[key]["lane"] + "_calls", calls)
            record_property(INPUTS[key]["lane"] + "_area_normal_n", audit["normal"])
            record_property(INPUTS[key]["lane"] + "_support_n", audit["support"])


def test_loaded_rr_entry_closes_with_existing_budget_and_gates():
    """Portable public initialization from the first rejected half-compensation step."""
    import mujoco as mj

    original = next(scene for scene in manipulation_scenes() if scene.key == "pusht-planar")
    assert original.source_sha256 == SOURCE_SHA
    model = mj.MjModel.from_xml_string(original.mjcf)
    source = dict(
        q=(
            -0.6002522110939026,
            0.9449527859687805,
            0.5189886093139648,
            0.00947501789778471,
            0.014993463642895222,
            0.9987941384315491,
            -9.678622154751793e-05,
            0.0002173582761315629,
            -0.049094825983047485,
        ),
        v=(
            0.07553205639123917,
            -0.05074348300695419,
            0.008799377828836441,
            0.028477977961301804,
            0.002139165299013257,
            -0.004497183486819267,
            0.03524314984679222,
            -0.10292518138885498,
        ),
    )
    initial, packed = _legal_initial(model, source, time=3.7190001766430214)
    spec, asset = build_scene_spec(original.mjcf), build_side_asset(model)
    world = MuJoCoTyxWorldSpec(6, spec.key, initial)
    with MuJoCoTyxHeterogeneousBatch((spec,), (world,), mode="cuda") as batch:
        scene = MuJoCoTyxHeterogeneousAreaPressureScene(batch, {spec.key: (asset,)})
        batch.set_controls({6: MuJoCoControl([0.6415153741836548, 0.3015781044960022])})
        before = batch.integration_snapshot()[6]
        np.testing.assert_array_equal(before.q, packed)
        revision = batch.checkpoint_revision
        assert scene.step(H, expected_revision=revision) == {6: True}
        after = batch.integration_snapshot()[6]
        assert batch.checkpoint_revision == revision + 1
        closure = after.last_step.raw_contact_fields["area_friction_solver"]["raw_diagnostics"]
        calls = int(closure["meta"][2])
        assert 1 <= calls <= 25
        assert closure["trace_meta"][calls - 1, 2] == 1
        assert closure["trace"][calls - 1, 10] <= np.float32(1e-6)
        assert closure["trace"][calls - 1, 11] <= np.float32(1e-7)
        audit = _audit(model, asset, before, after, scene.last_geometry[6][0])
        assert audit["normal"] > 0 and audit["support"] > 0
        phases = closure["trace_meta"][:calls, 0]
        assert np.any(phases == 3)
        solver = after.last_step.raw_contact_fields["area_friction_solver"]
        owner = batch._buckets[batch.layout[6].bucket]
        for index, replacement, reason in (
            (int(np.flatnonzero(phases == 2)[0]), 3, "damped trial"),
            (int(np.flatnonzero(phases == 3)[0]), 2, "area-load source binding"),
        ):
            claimed = closure["trace_meta"].copy()
            claimed[index, 0] = replacement
            forged = _solver_receipt(
                after.last_step, {**solver, "raw_diagnostics": {**closure, "trace_meta": claimed}}
            )
            with pytest.raises(ValueError, match=reason):
                validate_friction_receipt(owner, 6, forged, owner._data[6])
